"""
Generates the KiCad schematic for ONE switch of the inverter: an isolated
UCC21750-Q1 gate driver, its isolated +15 V / -4 V supply, DESAT short-circuit
detection, Miller clamp, NTC temperature sensing, and four paralleled
C3M0021120K SiC MOSFETs with individual gate networks.

Component values come from the analysis (results/*.json), so the schematic
always matches the design that was simulated.

    python hardware/gen_gate_driver.py      ->  hardware/gate-driver/gate_driver.kicad_sch
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT))
import kisch  # noqa: E402
from sicinv.design import CHOICE  # noqa: E402

OUT = HERE / "gate-driver"
OUT.mkdir(exist_ok=True)
LIB = OUT / "sic_inverter.kicad_sym"

sw = json.loads((ROOT / "results" / "switching_design.json").read_text())
gd = json.loads((ROOT / "results" / "gate_driver.json").read_text())
RG_ON = sw["gate_resistor_choice"]["rg_on_ohm"]
RG_OFF = sw["gate_resistor_choice"]["rg_off_ohm"]
C_BLK = sw["short_circuit"]["c_blk_pF"]
N = CHOICE["n_par"]


def fmt_r(r):
    return f"{r:g}".replace(".", "R") if r < 10 else f"{r:g}"


# ---------------------------------------------------- project symbol library --
def pin(kind, x, y, ang, name, num):
    return (f'(pin {kind} line (at {x} {y} {ang}) (length 3.81) '
            f'(name "{name}" (effects (font (size 1.27 1.27)))) '
            f'(number "{num}" (effects (font (size 1.27 1.27)))))')


left = [("power_in", "VCC", 15), ("input", "IN+", 10), ("input", "IN-", 11), ("input", "RST/EN", 14),
        ("open_collector", "~{FLT}", 13), ("open_collector", "RDY", 12), ("output", "APWM", 16),
        ("power_in", "GND", 9)]
right = [("power_in", "VDD", 5), ("output", "OUTH", 4), ("output", "OUTL", 6), ("input", "CLMPI", 7),
         ("input", "DESAT", 2), ("input", "AIN", 1), ("power_in", "COM", 3), ("power_in", "VEE", 8)]
pins_txt = [pin(k, -15.24, 8.89 - 2.54 * i, 0, n, num) for i, (k, n, num) in enumerate(left)]
pins_txt += [pin(k, 15.24, 8.89 - 2.54 * i, 180, n, num) for i, (k, n, num) in enumerate(right)]
LIB.write_text(f'''(kicad_symbol_lib (version 20241209) (generator "gen_gate_driver")
  (symbol "UCC21750-Q1" (pin_names (offset 1.016)) (exclude_from_sim no) (in_bom yes) (on_board yes)
    (property "Reference" "U" (at -11.43 13.97 0) (effects (font (size 1.27 1.27)) (justify left)))
    (property "Value" "UCC21750-Q1" (at -11.43 -13.97 0) (effects (font (size 1.27 1.27)) (justify left)))
    (property "Footprint" "Package_SO:SOIC-16W_7.5x10.3mm_P1.27mm" (at 0 0 0) (effects (font (size 1.27 1.27)) (hide yes)))
    (property "Datasheet" "https://www.ti.com/lit/ds/symlink/ucc21750-q1.pdf" (at 0 0 0) (effects (font (size 1.27 1.27)) (hide yes)))
    (property "Description" "10 A isolated single-channel gate driver, DESAT, active Miller clamp, AEC-Q100, 5.7 kVrms reinforced" (at 0 0 0) (effects (font (size 1.27 1.27)) (hide yes)))
    (symbol "UCC21750-Q1_0_1"
      (rectangle (start -11.43 11.43) (end 11.43 -11.43) (stroke (width 0.254) (type default)) (fill (type background)))
      (polyline (pts (xy 0 11.43) (xy 0 -11.43)) (stroke (width 0.254) (type dash)) (fill (type none)))
    )
    (symbol "UCC21750-Q1_1_1"
      {chr(10).join(pins_txt)}
    )
  )
)
''', encoding="utf-8")

# --------------------------------------------------------------- schematic --
s = kisch.Schematic(f"Isolated gate driver - one switch ({N}x SiC MOSFET in parallel)",
                    "gate_driver", "A3", project_lib=LIB)
s.date, s.rev = "2026-10-07", "A"
s.comments = ["800 V SiC traction inverter - design study",
              f"Rg_on = {RG_ON:g} ohm, Rg_off = {RG_OFF:g} ohm per device; C_blk = {C_BLK:g} pF (from simulation)",
              "Values generated by hardware/gen_gate_driver.py from results/*.json"]
FP = {
    "R0805": "Resistor_SMD:R_0805_2012Metric", "R1206": "Resistor_SMD:R_1206_3216Metric",
    "C0805": "Capacitor_SMD:C_0805_2012Metric", "C1210": "Capacitor_SMD:C_1210_3225Metric",
    "SOD123": "Diode_SMD:D_SOD-123", "SMA": "Diode_SMD:D_SMA", "SOT23": "Package_TO_SOT_SMD:SOT-23",
    "SOT223": "Package_TO_SOT_SMD:SOT-223-3_TabPin2", "SOT23-6": "Package_TO_SOT_SMD:SOT-23-6",
    "TO247-4": "Package_TO_SOT_THT:TO-247-4_Vertical",
    "J8": "Connector_PinHeader_2.54mm:PinHeader_1x08_P2.54mm_Vertical",
}


def R(value, x, y, n1, n2, rot=0, fp="R0805"):
    return s.add("Device:R", "R", value, x, y, rot, {"1": n1, "2": n2}, FP[fp])


def C(value, x, y, n1, n2, rot=0, fp="C0805"):
    return s.add("Device:C", "C", value, x, y, rot, {"1": n1, "2": n2}, FP[fp])


def flag(net, x, y):
    s.add("power:PWR_FLAG", "#FLG", "PWR_FLAG", x, y, 0, {"1": net}, hide_value=True)


# ---- low-voltage (controller) side -------------------------------------------
s.text("LOW-VOLTAGE SIDE (vehicle 12 V domain, GND)", 20, 22, 2.2, True)
s.add("Connector_Generic:Conn_01x08", "J", "CTRL", 30, 60, 0,
      {"1": "+5V", "2": "PWM", "3": "EN", "4": "~{FLT}", "5": "RDY", "6": "APWM", "7": "GND", "8": "GND"},
      FP["J8"])
s.text("J1: +5V, PWM, EN, FLT (open drain), RDY, APWM (temperature), GND", 20, 84, 1.3)
R("100", 60, 45, "PWM", "IN_P", 90)
C("100p", 75, 52, "IN_P", "GND")
R("10k", 90, 52, "EN", "GND")
R("10k", 105, 52, "+5V", "~{FLT}")
R("10k", 120, 52, "+5V", "RDY")
C("1u", 60, 68, "+5V", "GND")
C("100n", 75, 68, "+5V", "GND")
s.text("RC deglitch on PWM; EN pulled low = output off if the controller resets", 20, 88, 1.3)
flag("+5V", 135, 40)
flag("GND", 145, 40)

# ---- isolated supply (crosses the barrier) -------------------------------------
s.text("ISOLATED BIAS SUPPLY: push-pull transformer, 19 V regulated, split into +15 V / -3.9 V", 20, 112, 2.0, True)
C("100n", 30, 150, "+5V", "GND")
C("10u", 45, 150, "+5V", "GND", fp="C1210")
s.add("Power_Management:SN6505BDBV", "U", "SN6505B-Q1", 85, 160, 0,
      {"1": "T_A", "2": "+5V", "3": "T_B", "4": "GND", "5": "+5V", "6": "GND"}, FP["SOT23-6"])
s.add("Device:Transformer_SP_2S", "T", "1:4.5 per half, reinforced", 170, 160, 0,
      {"1": "T_A", "2": "+5V", "3": "T_B", "4": "S1", "5": "VEE", "6": "VEE", "7": "S2"})
s.add("Device:D_Schottky", "D", "SS16 (60 V)", 200, 145, 0, {"1": "V_RAW", "2": "S1"}, FP["SMA"])
s.add("Device:D_Schottky", "D", "SS16 (60 V)", 200, 175, 0, {"1": "V_RAW", "2": "S2"}, FP["SMA"])
C("10u 50V", 215, 160, "V_RAW", "VEE", fp="C1210")
s.add("Regulator_Linear:LM317_SOT-223", "U", "LM317-type LDO", 242, 160, 0,
      {"3": "V_RAW", "2": "VDD", "1": "ADJ"}, FP["SOT223"])
R("240", 265, 150, "VDD", "ADJ")
R("3.4k", 265, 172, "ADJ", "VEE")
R("3k", 285, 150, "VDD", "COM")
s.add("Device:D_Zener", "D", "3.9 V", 285, 172, 90, {"1": "COM", "2": "VEE"}, FP["SOD123"])
for k, (n1, n2) in enumerate((("VDD", "COM"), ("VDD", "COM"), ("COM", "VEE"), ("COM", "VEE"))):
    C("10u 50V" if k % 2 == 0 else "100n", 305 + 13 * k, 160, n1, n2, fp="C1210" if k % 2 == 0 else "C0805")
for net, x in (("VEE", 365), ("COM", 377), ("V_RAW", 389)):   # VDD is driven by the LDO output
    flag(net, x, 150)
s.text("VDD - VEE = 1.25 V x (1 + 3.4k / 240) = 19.0 V  (LM317-type automotive LDO)", 195, 188, 1.3)
s.text("3.9 V Zener (BZT52C3V9-Q) sets COM above VEE:  VDD = +15.1 V, VEE = -3.9 V vs source", 195, 192, 1.3)
s.text("10 uF + 100 nF per rail at the driver pins (datasheet: > 10 uF)", 300, 175, 1.3)

# ---- the gate driver -------------------------------------------------------------
s.text("UCC21750-Q1  isolated gate driver", 150, 22, 2.0, True)
s.add("sic_inverter:UCC21750-Q1", "U", "UCC21750-Q1", 170, 60, 0,
      {"15": "+5V", "10": "IN_P", "11": "GND", "14": "EN", "13": "~{FLT}", "12": "RDY", "16": "APWM", "9": "GND",
       "5": "VDD", "4": "OUTH", "6": "OUTL", "7": "CLMPI", "2": "DESAT", "1": "AIN", "3": "COM", "8": "VEE"},
      "Package_SO:SOIC-16W_7.5x10.3mm_P1.27mm")

# DESAT short-circuit detection
s.text("DESAT: trips when Vds stays > ~7.9 V with the gate on", 200, 88, 1.4, True)
R("1k", 210, 100, "DESAT", "DS_A", 90)
s.add("Device:D", "D", "STTH112 (1200 V)", 232, 100, 180, {"2": "DS_A", "1": "DS_B"}, FP["SMA"])
s.add("Device:D", "D", "STTH112 (1200 V)", 256, 100, 180, {"2": "DS_B", "1": "SW"}, FP["SMA"])
C(f"{C_BLK:g}p C0G", 210, 115, "DESAT", "COM")
s.add("Device:D_Schottky", "D", "BAT46", 226, 115, 90, {"1": "DESAT", "2": "COM"}, FP["SOD123"])
s.text("C_blk sets the blanking time; two 1200 V diodes block the 850 V bus", 200, 128, 1.3)

# temperature sense through the isolated AIN channel
s.text("Temperature: 200 uA from AIN into an NTC on the cold plate", 275, 22, 1.4, True)
R("3.3k", 285, 38, "AIN", "NTC_A")
s.add("Device:Thermistor_NTC", "TH", "10k B3435", 300, 38, 0, {"1": "NTC_A", "2": "COM"}, FP["R0805"])
C("1n", 315, 38, "AIN", "COM")

# ---- gate networks + paralleled SiC MOSFETs -------------------------------------
s.text(f"POWER STAGE: {N}x C3M0021120K in parallel, one gate network each", 190, 200, 2.0, True)
for k in range(1, N + 1):
    x0 = 190 + (k - 1) * 36
    y0 = 226
    g, ks = f"G{k}", f"KS{k}"
    R(fmt_r(RG_ON), x0, y0 - 18, "OUTH", g, fp="R1206")
    R(fmt_r(RG_OFF), x0 + 8, y0 - 18, "OUTL", g, fp="R1206")
    s.add("Device:D_Schottky", "D", "BAT46", x0 + 16, y0 - 18, 90, {"1": "CLMPI", "2": g}, FP["SOD123"],
          hide_value=True)
    R("10k", x0, y0 + 2, g, ks)
    s.add("Diode:BAT54S", "D", "BAT54S", x0 + 8, y0 + 14, 0, {"1": "VEE", "2": "VDD", "3": g}, FP["SOT23"],
          hide_value=True)
    R("0R5", x0 - 5, y0 + 24, ks, "COM")
    s.add("Transistor_FET:C3M0075120K", "Q", "C3M0021120K", x0 + 24, y0 + 6, 0,
          {"1": "SW", "2": "DC-", "4": g, "3": ks}, FP["TO247-4"])
s.text("Each gate: Rg_on from OUTH, Rg_off from OUTL, BAT46 Schottky to the shared Miller clamp, 10k gate-source,",
       190, 260, 1.3)
s.text("BAT54S clamps the gate between VEE and VDD, 0.5 ohm Kelvin-source resistor", 190, 264, 1.3)
flag("SW", 395, 205)
flag("DC-", 395, 215)

# ---- isolation barrier + notes --------------------------------------------------
# the barrier runs through the parts that cross it: the driver IC and the transformer
for seg in (((170, 18), (170, 48)), ((170, 72), (170, 148)), ((170, 172), (170, 285))):
    s.polyline(list(seg))
s.text("ISOLATION BARRIER (reinforced)", 172, 282, 1.6, True)
notes = [
    "Design notes (all values from the simulation study in this repo):",
    f"- gate charge {gd['Qg_per_device_nC']:.0f} nC per device, drive power {gd['gate_power_per_switch_W']:.2f} W per switch at 20 kHz",
    f"- isolated supply 2 W (margin {gd['supply_margin_x']:.1f}x); peak source/sink {gd['peak_source_A']:.1f} / {gd['peak_sink_A']:.1f} A",
    f"- DESAT delay {gd['desat_delay_us']['typ']:.2f} us typ / {gd['desat_delay_us']['worst']:.2f} us worst; CMTI margin {gd['CMTI_margin_x']:.1f}x",
    "- keep HV nets (SW, DC-, DS_B) >= 8 mm from the LV side; slot the PCB under U1 and T1",
]
for i, line in enumerate(notes):
    s.text(line, 20, 215 + 5 * i, 1.4, i == 0)

s.write(OUT / "gate_driver.kicad_sch")
(OUT / "sym-lib-table").write_text(
    '(sym_lib_table\n  (version 7)\n  (lib (name "sic_inverter")(type "KiCad")(uri "${KIPRJMOD}/sic_inverter.kicad_sym")'
    '(options "")(descr "Project symbols"))\n)\n')
pro = OUT / "gate_driver.kicad_pro"
if not pro.exists():
    pro.write_text(json.dumps({"meta": {"filename": "gate_driver.kicad_pro", "version": 1},
                               "schematic": {"legacy_lib_dir": "", "legacy_lib_list": []}}, indent=2))
print("wrote", OUT / "gate_driver.kicad_sch")
